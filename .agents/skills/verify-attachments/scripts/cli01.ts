import assert from "node:assert/strict";
import { spawn, spawnSync, type ChildProcess } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../../..");
const evidence = resolve(process.argv[2] ?? "");
const binaries = JSON.parse(readFileSync(join(root, ".scratch/bin/build.json"), "utf8"));
assert.ok(process.argv[2]);
mkdirSync(evidence, { recursive: false });
const scratch = mkdtempSync(join(tmpdir(), "todo-cli01-"));
const home = join(scratch, "home");
mkdirSync(home);
const env = { ...process.env, HOME: home, TODO_DB: join(scratch, "todo.db") };
const actions: unknown[] = [];
let server: ChildProcess | undefined;
let log = "";
const cli = (args: string[], expected = 0, input?: string) => {
  const result = spawnSync(binaries.cli, ["--profile", "work", ...args], { env, input, encoding: "utf8", timeout: 60000 });
  actions.push({ args, exit: result.status, stdout: result.stdout, stderr: result.stderr });
  assert.equal(result.status, expected, result.stdout + result.stderr);
  return result.stdout;
};
const json = (args: string[], expected = 0) => JSON.parse(cli([...args, "--format", "json"], expected));
try {
  cli(["init", "--password-stdin"], 0, "CLI01 scratch passphrase\n");
  cli(["login", "--password-stdin"], 0, "CLI01 scratch passphrase\n");
  const target = json(["add", "Adopt me", "--priority", "P1", "--due", "2026-12-01"]).task;
  const uri = "t3-thread://v2/host/thread";
  const attached = json(["attach", target.id, uri]);
  assert.equal(attached.task.attachments[0].url, uri);
  const file = join(scratch, "draft.md");
  writeFileSync(file, "draft\n");
  const created = json(["add", "Created with references", "--attach", file, "--link", uri, "--label", "jira"]).task;
  assert.equal(created.attachments.length, 2);
  assert.equal(created.attachments[0].path, file);
  assert.equal(created.attachments[1].url, uri);
  assert.equal(created.attachments[1].label, "jira");
  json(["add", "Must not exist", "--attach", join(scratch, "missing")], 2);
  assert.equal(json(["list"]).tasks.some((t: { title: string }) => t.title === "Must not exist"), false);
  json(["add", "Bad URI must not exist", "--link", "https://[invalid"], 2);
  assert.equal(json(["list"]).tasks.some((t: { title: string }) => t.title === "Bad URI must not exist"), false);
  const importFile = join(scratch, "import.json");
  const item = { external_id: "cli01:adopt", task_id: target.id, from_version: 1, title: "Adopted" };
  writeFileSync(importFile, JSON.stringify([item]));
  const stale = json(["import", importFile], 4);
  assert.equal(stale.items[0].error.code, "occ_conflict");
  assert.match(stale.items[0].error.message, /no external id yet/i);
  writeFileSync(importFile, JSON.stringify([{ ...item, from_version: 2 }]));
  assert.equal(json(["import", importFile, "--dry-run"]).items[0].outcome, "updated");
  assert.equal(json(["show", target.id]).task.external_id ?? null, null);
  assert.equal(json(["import", importFile]).items[0].outcome, "updated");
  const adopted = json(["show", target.id]).task;
  assert.equal(adopted.id, target.id);
  assert.equal(adopted.priority, "P1");
  assert.equal(adopted.due_at, "2026-12-01");
  writeFileSync(importFile, JSON.stringify([{ external_id: "cli01:adopt", title: "Later update", attachments: [{ kind: "link", url: "mailto:owner@example.com" }] }, { external_id: "bad:path", title: "No orphan", attachments: [{ kind: "file", path: join(scratch, "missing") }] }]));
  const report = json(["import", importFile], 2);
  assert.equal(report.items[0].task_id, target.id);
  assert.equal(report.items[1].outcome, "rejected");
  assert.equal(json(["list"]).tasks.some((t: { title: string }) => t.title === "No orphan"), false);
  const batchFile = join(scratch, "attach.json");
  const version = json(["show", target.id]).task.row_version;
  writeFileSync(batchFile, JSON.stringify({ items: [{ task_id: target.id, from_version: version, attachments: [{ kind: "link", url: uri }] }, { task_id: created.id, from_version: created.row_version, attachments: [{ kind: "link", url: "https://example.com/batch" }, { kind: "file", path: file }] }] }));
  const dry = json(["attach-many", batchFile, "--dry-run"]);
  assert.deepEqual(dry.items.map((r: { outcome: string }) => r.outcome), ["unchanged", "attached"]);
  assert.equal(json(["show", created.id]).task.row_version, created.row_version);
  const batch = json(["attach-many", batchFile]);
  assert.equal(batch.items[1].attached, 2);
  assert.equal(json(["show", created.id]).task.row_version, 3);
  assert.deepEqual(batch.items.map((r: { outcome: string }) => r.outcome), ["unchanged", "attached"]);
  assert.deepEqual(json(["attach-many", batchFile], 4).items.map((r: { outcome: string }) => r.outcome), ["unchanged", "rejected"]);
  for (const name of ["attach-many", "attach-many-input", "import-item"]) assert.ok(json(["schema", name]));
  server = spawn(binaries.server, [], { env: { ...env, TODO_PORT: "0" }, stdio: ["ignore", "pipe", "pipe"] });
  writeFileSync(join(evidence, "server.json"), JSON.stringify({ pid: server.pid, binary: binaries.server, scratch }));
  server.stdout?.on("data", chunk => { log += chunk.toString(); });
  server.stderr?.on("data", chunk => { log += chunk.toString(); });
  const deadline = Date.now() + 60000;
  while (!/Listening on (http:\/\/127\.0\.0\.1:\d+)/.test(log)) { assert.ok(Date.now() < deadline && server.exitCode === null, log); await new Promise(r => setTimeout(r, 40)); }
  const base = /Listening on (http:\/\/127\.0\.0\.1:\d+)/.exec(log)?.[1];
  assert.ok(base);
  let credential = "";
  const http = (path: string, body: unknown, expected = 200) => {
    const result = spawnSync("curl", ["--silent", "--show-error", "--max-time", "10", "-w", "\n%{http_code}", "-H", "Content-Type: application/json", ...(credential ? ["-H", `Authorization: Bearer ${credential}`] : []), "--data-binary", "@-", base + path], { input: JSON.stringify(body), encoding: "utf8" });
    assert.equal(result.status, 0, result.stderr);
    const split = result.stdout.lastIndexOf("\n");
    const status = Number(result.stdout.slice(split + 1));
    const response = JSON.parse(result.stdout.slice(0, split));
    if (path !== "/auth/sessions") actions.push({ path, body, status, response });
    assert.equal(status, expected, JSON.stringify(response));
    return response;
  };
  credential = http("/auth/sessions", { passphrase: "CLI01 scratch passphrase" }).credential;
  const httpTask = http("/profiles/work/tasks", { title: "HTTP references", attachments: [{ kind: "link", url: "urn:todo:http" }, { kind: "file", path: file }] });
  assert.equal(httpTask.attachments[0].url, "urn:todo:http");
  http("/profiles/work/tasks", { title: "HTTP no orphan", attachments: [{ kind: "file", path: join(scratch, "missing") }] }, 422);
  assert.equal(json(["list"]).tasks.some((t: { title: string }) => t.title === "HTTP no orphan"), false);
  const httpBatch = { items: [{ task_id: httpTask.id, from_version: 1, attachments: [{ kind: "link", url: uri }, { kind: "link", url: "mailto:owner@example.com" }] }] };
  assert.equal(http("/profiles/work/attachments/batch", { ...httpBatch, dry_run: true }).items[0].outcome, "attached");
  assert.equal(json(["show", httpTask.id]).task.row_version, 1);
  assert.equal(http("/profiles/work/attachments/batch", httpBatch).items[0].current_version, 3);
  assert.equal(http("/profiles/work/attachments/batch", httpBatch).items[0].error.code, "occ_conflict");
  const adoption = { external_id: "http:adopted", task_id: httpTask.id, from_version: 3, title: "HTTP adopted", attachments: [{ kind: "link", url: "t3-thread://v2/http/adopted" }] };
  assert.equal(http("/profiles/work/import", { items: [adoption], dry_run: true }).items[0].outcome, "updated");
  assert.equal(http("/profiles/work/import", { items: [adoption] }).items[0].outcome, "updated");
  assert.equal(json(["show", httpTask.id]).task.external_id, "http:adopted");
  writeFileSync(join(evidence, "result.json"), JSON.stringify({ status: "PASS", provenance: binaries, cases: ["URI", "atomic-create", "adoption", "import-attachments", "bulk-preview", "bulk-idempotence", "OCC", "schema", "HTTP"] }, null, 2));
} finally {
  if (server && server.exitCode === null && server.signalCode === null) {
    const exited = new Promise<void>(r => server?.once("exit", () => r()));
    server.kill("SIGTERM");
    await Promise.race([exited, new Promise(r => setTimeout(r, 2000))]);
    if (server.exitCode === null && server.signalCode === null) server.kill("SIGKILL");
    await exited;
  }
  writeFileSync(join(evidence, "server.log"), log);
  writeFileSync(join(evidence, "actions.json"), JSON.stringify(actions, null, 2));
  rmSync(scratch, { recursive: true, force: true });
}
