import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { resolve } from 'node:path';
const [before, after, cliBefore, cliAfter, manifest, evidence] = process.argv.slice(2);
assert.ok(before && after && cliBefore && cliAfter && manifest && evidence);
const scratch = resolve('.scratch/integ-server');
mkdirSync(scratch, { recursive: true });
let source = readFileSync('apps/server/scripts/read-scope-stream-control.ts', 'utf8');
const begin = '    } else if (scenario === "restore") {\n      writeFileSync(gate, "closed");';
assert.equal(source.split(begin).length, 2);
source = source.replace(begin, begin + '\n      cliWrite("work", uuids[1] ?? "", "Private Purged before restore");');
const afterSnapshot = '      cliWrite("work", uuids[0] ?? "", "Rolled back by restore");';
assert.equal(source.split(afterSnapshot).length, 2);
source = source.replace(afterSnapshot, `      const purged = spawnSync(resolve(cli), ["--db", path, "--profile", "work", "--credential-profile", "control", "--format", "json", "rm", uuids[1] ?? "", "--expected-version", "1", "--force"], { env: { ...process.env, HOME: home }, encoding: "utf8", timeout: 10000 });
      assert.equal(purged.status, 0, purged.stdout + purged.stderr);
${afterSnapshot}`);
const afterRestore = '      cliWrite("work", uuids[2] ?? "", "After restore");';
assert.equal(source.split(afterRestore).length, 2);
source = source.replace(afterRestore, `      const purgedHistory = await request("GET", "/profiles/work/tasks/" + uuids[1] + "/history");
      assert.equal(JSON.stringify(purgedHistory).includes("Private Purged before restore"), false, "restored History keeps Purge redaction");
      assert.ok(Array.isArray(purgedHistory));
      assert.deepEqual(purgedHistory.map(row => row.event.kind), ["TaskHistoryRedacted", "TaskHistoryRedacted", "TaskHistoryRedacted"]);
      const restoredTasks = await request("GET", "/profiles/work/tasks");
      assert.ok(Array.isArray(restoredTasks));
      assert.equal(restoredTasks.some(task => task.id === uuids[1]), false, "pre-Purge Snapshot never resurrects the Purged Task");
${afterRestore}`);
const driver = scratch + '/restore-purge-control.ts';
writeFileSync(driver, source);
const result = spawnSync('bun', [driver, before, after, cliBefore, cliAfter, manifest, evidence], { env: { ...process.env, READ_STREAM_SCENARIOS: 'restore' }, stdio: 'inherit' });
process.exitCode = result.status ?? 1;
