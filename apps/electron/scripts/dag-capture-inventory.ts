export function assertDagCaptureInventory(
  entries: readonly { state: string; layout: string; appearance: string }[],
) {
  const expected = groups.flatMap((group) =>
    group.states.flatMap((state) =>
      group.layouts.flatMap((layout) =>
        ["light", "dark"].map(
          (appearance) => `${state}/${layout}/${appearance}`,
        ),
      ),
    ),
  );
  assert.equal(
    expected.length,
    636,
    "Register every DAG fixture and update its literal capture count together",
  );
  const actual = entries.map(
    (entry) => `${entry.state}/${entry.layout}/${entry.appearance}`,
  );
  assert.equal(
    new Set(actual).size,
    actual.length,
    "Duplicate DAG capture identity",
  );
  assert.deepEqual(
    actual.toSorted(),
    expected.toSorted(),
    "DAG capture inventory must include every registered state, layout and appearance exactly once",
  );
}
