#!/usr/bin/env python3
"""The generated Swift client must be what generate-api.sh made from the document beside it.

  python3 apps/macos/scripts/generated-sources.py           check (root check, make sign-desktop)
  python3 apps/macos/scripts/generated-sources.py --write   end of generate-api.sh only

swift-contract.ts checks that apps/macos/API/Sources/TodoAPI/openapi.json is the normalized server
document and that ContractIdentity.swift names its contract. It does not look at the Swift files
generated from that document, so a hand edit of GeneratedSources passed it (server seat N6,
follow-up 67). generate-api.sh records here, after generating, the SHA-256 of that document and of
every file in GeneratedSources; the check refuses a document or a generated file that differs from
the record, and a file added to or missing from GeneratedSources. Run --write nowhere else: a
record written over hand-edited sources would bless them.

An optional argument names another checkout root (used by controls on a scratch copy).
"""
import hashlib
import json
import sys
from pathlib import Path

args = [a for a in sys.argv[1:] if a != '--write']
root = Path(args[0]).resolve() if args else Path(__file__).resolve().parents[3]
api = root / 'apps/macos/API'
document = api / 'Sources/TodoAPI/openapi.json'
generated = api / 'Sources/TodoAPI/GeneratedSources'
record = api / 'generated-sources.json'


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def observed() -> dict:
    return {
        'document': {'path': str(document.relative_to(root)), 'sha256': sha(document)},
        'generated': {path.name: sha(path) for path in sorted(generated.glob('*.swift'))},
    }


if '--write' in sys.argv[1:]:
    current = observed()
    record.write_text(json.dumps({
        'about': 'Written by apps/macos/scripts/generated-sources.py --write at the end of generate-api.sh: the Swift files in GeneratedSources and the document they were generated from. The root check refuses any difference.',
        **current,
    }, indent=2) + '\n')
    print(f"Generated sources recorded: {len(current['generated'])} files from {current['document']['sha256'][:12]}")
    raise SystemExit(0)

if not record.exists():
    raise SystemExit(f'{record.relative_to(root)} is missing: run apps/macos/scripts/generate-api.sh')
expected = json.loads(record.read_text())
current = observed()
problems = []
if current['document'] != expected['document']:
    problems.append(f"{expected['document']['path']} differs from the document the Swift client was generated from")
for name in sorted(set(expected['generated']) | set(current['generated'])):
    if name not in current['generated']:
        problems.append(f'GeneratedSources/{name} is missing')
    elif name not in expected['generated']:
        problems.append(f'GeneratedSources/{name} was not generated by generate-api.sh')
    elif current['generated'][name] != expected['generated'][name]:
        problems.append(f'GeneratedSources/{name} differs from what generate-api.sh wrote (a hand edit?)')
if problems:
    raise SystemExit('The generated Swift client is not what generate-api.sh made; regenerate with apps/macos/scripts/generate-api.sh:\n- ' + '\n- '.join(problems))
print(f"Generated Swift sources match their record: {len(current['generated'])} files from {current['document']['sha256'][:12]}.")
