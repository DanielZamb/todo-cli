import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

const source = "https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt";
const response = await fetch(source);
if (!response.ok)
  throw new Error(`Unicode download failed: ${response.status}`);
const bytes = await response.text();
const sha256 = createHash("sha256").update(bytes).digest("hex");
const expected =
  "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183";
if (sha256 !== expected)
  throw new Error(`Unicode source hash mismatch: ${sha256}`);
const pairs = bytes.split("\n").flatMap((line) => {
  const match = /^([0-9A-F]+); [CF]; ([0-9A-F ]+);/u.exec(line);
  if (!match?.[1] || !match[2]) return [];
  return [
    [
      String.fromCodePoint(Number.parseInt(match[1], 16)),
      String.fromCodePoint(
        ...match[2].split(" ").map((hex) => Number.parseInt(hex, 16)),
      ),
    ],
  ];
});
writeFileSync(
  new URL("../src/task-search-case-fold.ts", import.meta.url),
  `// Generated by packages/domain/scripts/generate-task-search-case-fold.ts.\n// Unicode 17.0.0 default full case fold (C + F, excluding Turkic T).\n// Source: ${source}\n// SHA-256: ${sha256}\n// License: https://www.unicode.org/license.txt\nexport const taskSearchCaseFold: ReadonlyMap<string, string> = new Map([\n${pairs.map(([from, to]) => `  [${JSON.stringify(from)}, ${JSON.stringify(to)}],`).join("\n")}\n]);\n`,
);
