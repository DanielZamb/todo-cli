import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { OpenApi } from "effect/http-api";
import { TodoApi } from "../src/index.ts";

const canonical = (value: unknown): string => {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value !== null && typeof value === "object")
    return `{${Object.entries(value)
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([key, entry]) => `${JSON.stringify(key)}:${canonical(entry)}`)
      .join(",")}}`;
  return JSON.stringify(value) ?? "null";
};
const document = OpenApi.fromApi(TodoApi);
const contract = createHash("sha256").update(canonical(document)).digest("hex");
const files = [
  [
    new URL("../openapi.json", import.meta.url),
    `${JSON.stringify(document, null, 2)}\n`,
  ],
  [
    new URL("../src/contract.ts", import.meta.url),
    `// Generated by scripts/openapi.ts.\nexport const CONTRACT_ID =\n  "${contract}";\n`,
  ],
  [
    new URL(
      "../../../apps/macos/API/Sources/TodoAPI/ContractIdentity.swift",
      import.meta.url,
    ),
    `// Generated by packages/api/scripts/openapi.ts.\npublic enum TodoContract {\n    public static let id = "${contract}"\n}\n`,
  ],
] as const;
const checking = process.argv.includes("--check");
for (const [path, content] of files) {
  if (!checking) writeFileSync(path, content);
  else if (path.pathname.endsWith("openapi.json")) {
    if (
      canonical(JSON.parse(readFileSync(path, "utf8"))) !== canonical(document)
    )
      throw new Error(
        "OpenAPI drift. Run pnpm --filter @todo/api openapi and regenerate the Swift API.",
      );
  } else if (readFileSync(path, "utf8") !== content)
    throw new Error(
      `Contract identity drift: ${path.pathname}. Run pnpm --filter @todo/api openapi.`,
    );
}
